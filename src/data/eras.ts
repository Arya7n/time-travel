export function eraById(id: Era['id']): Era {
  return ERAS.find((era) => era.id === id) ?? ERAS[6]
}

export function eraAtYear(year: number): Era {
  if (year < 500) return ERAS[0]
  if (year < 1500) return ERAS[1]
  if (year < 1900) return ERAS[2]
  if (year < 1930) return ERAS[3]
  if (year < 1970) return ERAS[4]
  if (year < 2005) return ERAS[5]
  if (year <= 2026) return ERAS[6]
  return ERAS[7]
}

export function eraWeight(year: number, era: Era): number {
  if (year < era.startYear - 80 || year > era.endYear + 80) return 0
  if (year >= era.startYear && year <= era.endYear) {
    const edge = Math.min(year - era.startYear, era.endYear - year)
    return 0.72 + 0.28 * Math.min(1, edge / 40)
  }
  const dist =
    year < era.startYear ? era.startYear - year : year - era.endYear
  return Math.max(0, 1 - dist / 80)
}
